async def generate_one(filename, text, sem):
    async with sem:
        path = os.path.join(OUTPUT_DIR, f"{filename}.mp3")
        if os.path.isfile(path) and os.path.getsize(path) > 0:
            print(f"  ⏭️  {filename}.mp3 existe déjà")
            return
        try:
            communicate = edge_tts.Communicate(text, VOICE, rate=RATE)
            await communicate.save(path)
            print(f"  ✅ {filename}.mp3")
        except Exception as e:
            print(f"  ❌ {filename} : {e}")


async def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    print(f"🎙️  Voix : {VOICE}")
    print(f"📁  Dossier : {OUTPUT_DIR}/")
    print(f"🔊  {len(AUDIO_ITEMS)} fichiers à générer\n")

    sem = asyncio.Semaphore(5)
    await asyncio.gather(*[generate_one(n, t, sem) for n, t in AUDIO_ITEMS])
    print(f"\n✨ Terminé !")


if __name__ == "__main__":
    asyncio.run(main())
